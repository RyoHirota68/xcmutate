import Foundation
import MutatorCore

/// A Swift file that is not mutated, and why.
public struct ExcludedFile: Codable, Sendable, Hashable {
    public var file: String
    /// `test-code`, `test-directory`, `generated-code`, `package-manifest`, `build-or-dependency-directory`,
    /// `fixtures-directory` or `config-exclude`.
    public var reason: String
    /// The pattern or marker that matched.
    public var detail: String?

    public init(file: String, reason: String, detail: String? = nil) {
        self.file = file
        self.reason = reason
        self.detail = detail
    }
}

/// Decides which Swift files are mutated when no files are given on the command line.
///
/// Default rules (each excluded file is reported; nothing is dropped silently):
/// - `Package.swift`; files under `.build`, `DerivedData`, `.swiftpm`, `Pods`, `Carthage`, `Fixtures`
/// - test code: the file imports a test framework (`XCTest`, `Testing`, `Quick`, `Nimble`) or uses `@testable import`
/// - a directory named like a test target (`Tests`, `…Tests`) **that contains at least one such file**: its other
///   files (helpers, mocks) are excluded too
/// - generated code: a header comment in the first lines says so (`DO NOT EDIT`, `@generated`, `Generated by`, …)
///
/// A name alone is never enough: `ABTest.swift` or a `SplitTests/` directory holding product code is mutated.
/// (An earlier rule dropped any file ending in `Test.swift` / `Tests.swift` and any directory ending in `Tests` was dropped
/// without a word.)
///
/// `exclude` patterns from `xcmutate.config.json` are applied afterwards, in order; the last match wins.
/// A pattern starting with `!` includes the file again, even if a default rule excluded it.
public enum FileSelector {
    public struct Selection: Sendable {
        public var included: [String]
        public var excluded: [ExcludedFile]
    }

    static let skippedDirectories: Set<String> = [".build", "DerivedData", ".swiftpm", "Pods", "Carthage"]
    static let headerLines = 15

    public static func select(paths: [String], patterns: [String] = [], read: (String) -> String?) -> Selection {
        var contents: [String: String] = [:]
        for path in paths { contents[path] = read(path) ?? "" }
        let testImporting = Set(paths.filter { importsTestFramework(contents[$0] ?? "") })
        // Directories named like a test target that hold at least one file importing a test framework.
        var testDirectories: Set<String> = []
        for path in testImporting {
            if let directory = conventionalTestDirectory(of: path) { testDirectories.insert(directory) }
        }
        let compiled = patterns.map(GlobPattern.init)

        var included: [String] = []
        var excluded: [ExcludedFile] = []
        for path in paths.sorted() {
            var verdict = defaultReason(path, source: contents[path] ?? "", testImporting: testImporting, testDirectories: testDirectories)
            for pattern in compiled where pattern.matches(path) {
                verdict = pattern.negated ? nil : ExcludedFile(file: path, reason: "config-exclude", detail: pattern.text)
            }
            if let verdict { excluded.append(verdict) } else { included.append(path) }
        }
        return Selection(included: included, excluded: excluded)
    }

    static func defaultReason(_ path: String, source: String, testImporting: Set<String>, testDirectories: Set<String>) -> ExcludedFile? {
        let components = path.split(separator: "/").map(String.init)
        let name = components.last ?? path
        if name == "Package.swift" || (name.hasPrefix("Package@swift-") && name.hasSuffix(".swift")) {
            return ExcludedFile(file: path, reason: "package-manifest")
        }
        if let directory = components.dropLast().first(where: { skippedDirectories.contains($0) }) {
            return ExcludedFile(file: path, reason: "build-or-dependency-directory", detail: directory)
        }
        if components.dropLast().contains("Fixtures") {
            return ExcludedFile(file: path, reason: "fixtures-directory", detail: "Fixtures")
        }
        if testImporting.contains(path) {
            return ExcludedFile(file: path, reason: "test-code", detail: "imports a test framework")
        }
        if let directory = conventionalTestDirectory(of: path), testDirectories.contains(directory) {
            return ExcludedFile(file: path, reason: "test-directory", detail: directory)
        }
        if let marker = generatedMarker(in: source) {
            return ExcludedFile(file: path, reason: "generated-code", detail: marker)
        }
        return nil
    }

    /// The outermost directory of the path that is named like a test target (`Tests`, `AppTests`, `AppUITests`).
    public static func conventionalTestDirectory(of path: String) -> String? {
        let components = path.split(separator: "/").map(String.init).dropLast()
        guard let index = components.firstIndex(where: { $0 == "Tests" || $0.hasSuffix("Tests") }) else { return nil }
        return components[...index].joined(separator: "/")
    }

    static func importsTestFramework(_ source: String) -> Bool {
        TestImports.importsTestFramework(source)
    }

    static let generatedMarkers = ["do not edit", "@generated", "generated by", "generated using", "code generated",
                                   "auto-generated", "autogenerated", "automatically generated"]

    /// A marker of generated code in a comment among the first lines of the file.
    /// `swiftlint:disable all` alone is not treated as one: hand-written files use it too, and dropping product
    /// code silently is the failure this type exists to prevent.
    static func generatedMarker(in source: String) -> String? {
        for line in source.split(separator: "\n", omittingEmptySubsequences: false).prefix(headerLines) {
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            guard trimmed.hasPrefix("//") || trimmed.hasPrefix("/*") || trimmed.hasPrefix("*") else { continue }
            let lower = trimmed.lowercased()
            if let marker = generatedMarkers.first(where: { lower.contains($0) }) { return marker }
        }
        return nil
    }
}

/// A gitignore-style pattern: `*` and `?` do not cross `/`, `**` does; a pattern without `/` matches a name at any
/// depth; a pattern that matches a directory matches everything below it; a leading `!` negates.
public struct GlobPattern: Sendable {
    public var text: String
    public var negated: Bool
    private let regex: NSRegularExpression?

    public init(_ raw: String) {
        text = raw
        var pattern = raw.trimmingCharacters(in: .whitespaces)
        negated = pattern.hasPrefix("!")
        if negated { pattern.removeFirst() }
        while pattern.hasSuffix("/") { pattern.removeLast() }
        let anchored = pattern.contains("/")
        if pattern.hasPrefix("/") { pattern.removeFirst() }
        if pattern.hasPrefix("./") { pattern.removeFirst(2) }

        var body = ""
        var index = pattern.startIndex
        while index < pattern.endIndex {
            let c = pattern[index]
            if c == "*" {
                let next = pattern.index(after: index)
                if next < pattern.endIndex, pattern[next] == "*" {
                    let after = pattern.index(after: next)
                    if after < pattern.endIndex, pattern[after] == "/" {
                        body += "(?:.*/)?"
                        index = pattern.index(after: after)
                    } else {
                        body += ".*"
                        index = after
                    }
                    continue
                }
                body += "[^/]*"
            } else if c == "?" {
                body += "[^/]"
            } else {
                body += NSRegularExpression.escapedPattern(for: String(c))
            }
            index = pattern.index(after: index)
        }
        regex = pattern.isEmpty ? nil : try? NSRegularExpression(pattern: (anchored ? "^" : "^(?:.*/)?") + body + "(?:/.*)?$")
    }

    public func matches(_ path: String) -> Bool {
        guard let regex else { return false }
        return regex.firstMatch(in: path, range: NSRange(location: 0, length: (path as NSString).length)) != nil
    }
}
