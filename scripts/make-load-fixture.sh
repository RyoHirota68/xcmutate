#!/bin/bash
# Makes a copy of the fixture (Fixtures/SampleApp) with many slow tests added, to measure what a run costs in a
# project whose whole test run is long. The fixture itself runs its 94 tests in a fraction of a second, which hides
# every cost that grows with the length of a test run: the runs without mutants between mutants, the runs at the
# start of a shared process, the timeout of a mutant that never ends.
#
#   scripts/make-load-fixture.sh <out-dir> [--tests 1000] [--seconds 30] [--suites 20] [--twin-tests] [host options]
#
# <out-dir> must be outside this repository (a directory that git ignores is not copied into a work copy).
# The added tests are Swift Testing tests that only sleep: <seconds> in total, spread over <tests> tests in <suites>
# suites. They reach no mutant, so `--select-tests reach` never selects them for a mutant; they are part of every
# run of the whole selection.
#
# --twin-tests adds a copy of each test file of the measured code under another suite name, so that every mutant
# is reached by tests of two suites. (A mutant that exactly one test reaches is not narrowed without
# --shared-process: one baseline cannot tell code that one test calls from code that runs once per process. In
# the fixture nearly every mutant is reached by exactly one test, which real projects are not.)
#
# Host options, to reproduce ways in which a test host started by the tool (without xcodebuild) can differ from
# one started by xcodebuild:
#   --host-launch-seconds <n>      the app takes <n> seconds before it has finished launching
#   --host-exits-without-session   the app exits at launch when the tool started it (it finds the tool's driver
#                                  library in DYLD_INSERT_LIBRARIES): stands for an app that does not run unless
#                                  it was started the way it expects
#   --host-exits-when-busy <n>     the app ends itself when the tool started it and its main thread has not been
#                                  free for <n> seconds: stands for a watchdog that ends an app whose main thread
#                                  runs tests although the app was not started for testing
#   --main-thread-test-seconds <n> one XCTest test that keeps the main thread busy for <n> seconds
#   --principal-class              the test bundle names a principal class in its Info.plist, and a test fails
#                                  unless XCTest (or whoever loads the bundle) has created an instance of it
#
# The measurements themselves are run with scripts/measure-load.sh.
set -euo pipefail

if [[ $# -lt 1 ]]; then
  sed -n '2,24p' "$0" >&2
  exit 64
fi
OUT="$1"
shift
TESTS=1000
SECONDS_TOTAL=30
SUITES=20
TWIN=0
LAUNCH_SECONDS=0
EXIT_WITHOUT_SESSION=0
EXIT_WHEN_BUSY=0
PRINCIPAL=0
MAIN_THREAD_SECONDS=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --tests) TESTS="$2"; shift 2 ;;
    --seconds) SECONDS_TOTAL="$2"; shift 2 ;;
    --suites) SUITES="$2"; shift 2 ;;
    --twin-tests) TWIN=1; shift ;;
    --host-launch-seconds) LAUNCH_SECONDS="$2"; shift 2 ;;
    --host-exits-without-session) EXIT_WITHOUT_SESSION=1; shift ;;
    --host-exits-when-busy) EXIT_WHEN_BUSY="$2"; shift 2 ;;
    --principal-class) PRINCIPAL=1; shift ;;
    --main-thread-test-seconds) MAIN_THREAD_SECONDS="$2"; shift 2 ;;
    *) echo "unknown option: $1" >&2; exit 64 ;;
  esac
done

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
case "$(cd "$(dirname "$OUT")" 2>/dev/null && pwd)/" in
  "$ROOT"/*) echo "<out-dir> must be outside the repository ($ROOT)" >&2; exit 64 ;;
esac

rm -rf "$OUT"
mkdir -p "$OUT"
rsync -a --exclude SampleApp.xcodeproj "$ROOT/Fixtures/SampleApp/" "$OUT/"

python3 - "$OUT" "$TESTS" "$SECONDS_TOTAL" "$SUITES" "$LAUNCH_SECONDS" "$EXIT_WITHOUT_SESSION" "$EXIT_WHEN_BUSY" "$TWIN" "$PRINCIPAL" "$MAIN_THREAD_SECONDS" <<'PY'
import re
import sys
from pathlib import Path

out = Path(sys.argv[1])
tests, seconds, suites = int(sys.argv[2]), float(sys.argv[3]), int(sys.argv[4])
launch_seconds, exit_without_session, exit_when_busy = float(sys.argv[5]), sys.argv[6] == "1", float(sys.argv[7])

per_test = seconds / max(tests, 1)
lines = ["// Generated by scripts/make-load-fixture.sh. Tests that only take time.", "import Foundation", "import Testing", ""]
per_suite = -(-tests // suites)
made = 0
for suite in range(suites):
    count = min(per_suite, tests - made)
    if count <= 0:
        break
    lines.append(f"@Suite struct GeneratedLoad{suite:03d} {{")
    for test in range(count):
        lines.append(f"    @Test func load{test:04d}() {{ Thread.sleep(forTimeInterval: {per_test:.5f}) }}")
    lines.append("}")
    lines.append("")
    made += count
(out / "SampleAppTests" / "GeneratedLoadTests.swift").write_text("\n".join(lines))

if sys.argv[8] == "1":
    for name in ["SideEffectTests", "InfrastructureTests", "ReturnAndClosureCasesTests", "EquivalenceTests"]:
        text = (out / "SampleAppTests" / f"{name}.swift").read_text()
        for declared in re.findall(r"^(?:final class|@Suite struct|struct|class) (\w+)", text, flags=re.M):
            text = re.sub(rf"\b{declared}\b", declared + "Twin", text)
        (out / "SampleAppTests" / f"{name}Twin.swift").write_text("// Generated by scripts/make-load-fixture.sh: a copy under another suite name.\n" + text)

if float(sys.argv[10]) > 0:
    (out / "SampleAppTests" / "LoadMainThreadTests.swift").write_text(f"""// Generated by scripts/make-load-fixture.sh.
import XCTest

final class LoadMainThreadTests: XCTestCase {{
    func testKeepsTheMainThreadBusy() {{ Thread.sleep(forTimeInterval: {float(sys.argv[10])}) }}
}}
""")

if sys.argv[9] == "1":
    (out / "SampleAppTests" / "LoadPrincipal.swift").write_text("""// Generated by scripts/make-load-fixture.sh.
import Foundation
import Testing

/// Named as NSPrincipalClass of the test bundle: XCTest creates one instance when it loads the bundle.
@objc(LoadFixturePrincipal) final class LoadFixturePrincipal: NSObject {
    nonisolated(unsafe) static var made = false
    override init() {
        super.init()
        LoadFixturePrincipal.made = true
    }
}

@Suite struct LoadPrincipalTests {
    @Test func thePrincipalClassWasCreated() { #expect(LoadFixturePrincipal.made) }
}
""")
    project = out / "project.yml"
    text = project.read_text()
    marker = "        PRODUCT_BUNDLE_IDENTIFIER: dev.xcmutate.SampleAppTests\n        GENERATE_INFOPLIST_FILE: YES\n"
    assert marker in text
    project.write_text(text.replace(marker, marker + "        INFOPLIST_KEY_NSPrincipalClass: LoadFixturePrincipal\n", 1))

if launch_seconds > 0 or exit_without_session or exit_when_busy > 0:
    app = out / "SampleApp" / "App" / "SampleApp.swift"
    text = app.read_text()
    body = []
    if exit_without_session:
        body += [
            "        // Leaves at once when the tool started the app (its driver library is inserted)",
            "        if (ProcessInfo.processInfo.environment[\"DYLD_INSERT_LIBRARIES\"] ?? \"\").contains(\"XCMutateSharedProcess\") { exit(3) }",
        ]
    if launch_seconds > 0:
        body.append(f"        Thread.sleep(forTimeInterval: {launch_seconds})")
    if exit_when_busy > 0:
        body += [
            "        // Ends the app when the tool started it and the main thread has not been free for a while",
            "        let startedByTheTool = (ProcessInfo.processInfo.environment[\"DYLD_INSERT_LIBRARIES\"] ?? \"\").contains(\"XCMutateSharedProcess\")",
            "        let lastFree = LoadFixtureClock()",
            "        Timer.scheduledTimer(withTimeInterval: 0.2, repeats: true) { _ in lastFree.touch() }",
            "        if startedByTheTool {",
            "            Thread.detachNewThread {",
            f"                while true {{ Thread.sleep(forTimeInterval: 0.5); if lastFree.age() > {exit_when_busy} {{ exit(4) }} }}",
            "            }",
            "        }",
        ]
    init = "    init() {\n" + "\n".join(body) + "\n    }\n"
    marker = "struct SampleApp: App {\n"
    assert marker in text
    text = text.replace(marker, marker + init, 1)
    if exit_when_busy > 0:
        text += """
nonisolated final class LoadFixtureClock: @unchecked Sendable {
    private let lock = NSLock()
    private var last = Date()
    init() {}
    func touch() { lock.lock(); last = Date(); lock.unlock() }
    func age() -> TimeInterval { lock.lock(); defer { lock.unlock() }; return Date().timeIntervalSince(last) }
}
"""
    app.write_text(text)
print(f"{made} tests in {min(suites, made)} suites, {seconds:.0f}s in all, at {out}")
PY
