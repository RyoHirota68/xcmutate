#!/usr/bin/env python3
"""Writes the Swift files that hold the texts compiled into the executable.

usage: scripts/generate-agent-guide.py [--check]

  docs/agent-guide.md                           -> Sources/MutatorRunner/AgentGuideText.swift  (`xcmutate agent-guide`)
  .claude/skills/mutation-test-loop/SKILL.md    -> Sources/MutatorRunner/AgentSkillText.swift  (`xcmutate agent-guide --install claude`)

The release is one file, so nothing is looked up at run time. The Markdown files are the originals; run this script
after every change of one of them. A unit test fails when a Swift file and its original differ. --check: write
nothing, exit 1 if a Swift file is out of date.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEXTS = [
    ("docs/agent-guide.md", "Sources/MutatorRunner/AgentGuideText.swift", "AgentGuide",
     "The guide for coding agents that `xcmutate agent-guide` prints.", "The text of docs/agent-guide.md, byte for byte."),
    (".claude/skills/mutation-test-loop/SKILL.md", "Sources/MutatorRunner/AgentSkillText.swift", "AgentSkill",
     "The Claude Code skill that `xcmutate agent-guide --install claude` writes.",
     "The text of .claude/skills/mutation-test-loop/SKILL.md, byte for byte."),
]


def swift_literal(text: str) -> str:
    # A raw string with enough pound signs that nothing in the text can end it or start an interpolation
    pounds = "#"
    while '"""' + pounds in text or "\\" + pounds in text:
        pounds += "#"
    lines = text.split("\n")
    if lines[-1] == "":
        lines = lines[:-1]            # the final newline is added by the code, so the literal has no empty last line
    body = "\n".join(lines)
    return pounds + '"""\n' + body + '\n"""' + pounds


def render(source: str, name: str, summary: str, detail: str) -> str:
    with open(os.path.join(ROOT, source), encoding="utf-8") as handle:
        text = handle.read()
    if not text.endswith("\n"):
        sys.exit(source + " must end with a newline")
    return (
        "// Generated by scripts/generate-agent-guide.py from " + source + ". Do not edit: edit the "
        + ("guide" if name == "AgentGuide" else "skill") + " and run the script.\n"
        "\n"
        "/// " + summary + "\n"
        "public enum " + name + " {\n"
        "    /// " + detail + "\n"
        "    public static let text: String = "
        + swift_literal(text)
        + ' + "\\n"\n'
        "}\n"
    )


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for source, target, name, summary, detail in TEXTS:
        rendered = render(source, name, summary, detail)
        path = os.path.join(ROOT, target)
        if check:
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if current != rendered:
                stale.append(target)
        else:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(rendered)
    if stale:
        print(", ".join(stale) + " out of date: run scripts/generate-agent-guide.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
